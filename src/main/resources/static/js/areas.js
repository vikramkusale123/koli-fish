document.addEventListener("DOMContentLoaded", function () {

    // =========================================
    // ELEMENTS
    // =========================================
    const modal = document.getElementById("areaModal");
    const addButton = document.getElementById("addAreaButton");
    const closeButton = document.getElementById("closeAreaModal");
    const cancelButton = document.getElementById("cancelAreaButton");
    const form = document.getElementById("areaForm");
    const areaTable = document.getElementById("areaTable");

    const searchInput = document.getElementById("areaSearch");
    const searchInputSecondary = document.getElementById("areaSearchSecondary");

    const totalAreas = document.getElementById("totalAreas");
    const activeAreas = document.getElementById("activeAreas");
    const totalCustomers = document.getElementById("totalCustomers");
    const areaNameInput = document.getElementById("areaName");

    // =========================================
    // REMOVE OLD DUPLICATE FOOTER
    // =========================================
    function removeOldFooter() {
        const oldCount = document.getElementById("showingCount");

        if (oldCount) {
            const oldFooter = oldCount.closest(
                ".pagination-container, .table-pagination, .table-footer, .pagination-wrapper"
            );

            if (oldFooter && oldFooter.id !== "areaPagination") {
                oldFooter.remove();
            } else {
                oldCount.remove();
            }
        }

        // Remove any previous footer generated by this script
        // so that only one footer is displayed.
        const existingFooter = document.getElementById("areaPagination");

        if (existingFooter) {
            existingFooter.remove();
        }
    }

    removeOldFooter();

    // =========================================
    // DATA
    // =========================================
    let areas = [];
    let customers = [];

    // =========================================
    // INITIAL LOAD
    // =========================================
    loadData();

    async function loadData() {
        await loadAreas();
        await loadCustomers();

        updateStatistics();
        displayAreas();
    }

    // =========================================
    // LOAD AREAS
    // =========================================
    async function loadAreas() {
        try {
            const response = await fetch("/api/areas");

            if (!response.ok) {
                throw new Error("Unable to load areas");
            }

            const data = await response.json();
            areas = Array.isArray(data) ? data : [];

        } catch (error) {
            console.error("Area loading error:", error);
            areas = [];
        }
    }

    // =========================================
    // LOAD CUSTOMERS
    // =========================================
    async function loadCustomers() {
        try {
            const response = await fetch("/api/customers");

            if (!response.ok) {
                throw new Error("Unable to load customers");
            }

            const data = await response.json();
            customers = Array.isArray(data) ? data : [];

        } catch (error) {
            console.error("Customer loading error:", error);
            customers = [];
        }
    }

    // =========================================
    // DISPLAY AREAS
    // =========================================
    function displayAreas() {
        if (!areaTable) {
            console.error("areaTable not found");
            return;
        }

        const search = searchInput
            ? searchInput.value.toLowerCase().trim()
            : "";

        const secondarySearch = searchInputSecondary
            ? searchInputSecondary.value.toLowerCase().trim()
            : "";

        const activeSearch = secondarySearch || search;

        const filteredAreas = areas.filter(function (area) {
            return String(area.name || "")
                .toLowerCase()
                .includes(activeSearch);
        });

        areaTable.innerHTML = "";

        if (filteredAreas.length === 0) {
            areaTable.innerHTML = `
                <tr>
                    <td colspan="4">
                        <div class="area-empty">
                            <div class="empty-icon">📍</div>
                            <strong>No areas found</strong>
                            <p>Add an area to get started.</p>
                            <button
                                type="button"
                                class="primary-button"
                                id="emptyAreaButton">
                                + Add Area
                            </button>
                        </div>
                    </td>
                </tr>
            `;

            const emptyButton = document.getElementById("emptyAreaButton");

            if (emptyButton) {
                emptyButton.addEventListener("click", openModal);
            }

            updateShowingCount(0);
            return;
        }

        filteredAreas.forEach(function (area) {
            const customerCount = getCustomerCount(area.id);
            const row = document.createElement("tr");

            row.innerHTML = `
                <td>
                    <div class="area-name-cell">
                        <div>
                            <strong>${escapeHtml(area.name)}</strong>
                        </div>
                    </div>
                </td>

                <td>
                    <div class="customer-count">
                        <strong>${customerCount}</strong>
                        <span>
                            ${customerCount === 1 ? "customer" : "customers"}
                        </span>
                    </div>
                </td>

                <td>
                    <span class="area-status active">
                        <span class="status-dot"></span>
                        Active
                    </span>
                </td>

                <td>
                    <div class="area-actions">
                        <button
                            type="button"
                            class="area-edit-button"
                            title="Edit Area"
                            aria-label="Edit ${escapeHtml(area.name)}">
                            ✏️
                        </button>

                        <button
                            type="button"
                            class="area-delete-button"
                            title="Delete Area"
                            aria-label="Delete ${escapeHtml(area.name)}">
                            🗑️
                        </button>
                    </div>
                </td>
            `;

            const editButton = row.querySelector(".area-edit-button");
            const deleteButton = row.querySelector(".area-delete-button");

            editButton.addEventListener("click", function () {
                editArea(area);
            });

            deleteButton.addEventListener("click", function () {
                deleteArea(area.id);
            });

            areaTable.appendChild(row);
        });

        updateShowingCount(filteredAreas.length);
    }

    // =========================================
    // SINGLE FOOTER: SHOWING COUNT + ‹ 1 ›
    // =========================================
    function setupPaginationContainer() {
        let footer = document.getElementById("areaPagination");

        if (footer) {
            return footer;
        }

        const table = areaTable ? areaTable.closest("table") : null;

        if (!table) {
            console.error("Could not find the Areas table.");
            return null;
        }

        footer = document.createElement("div");
        footer.id = "areaPagination";

        footer.style.cssText = `
            display: flex;
            flex-wrap: wrap;
            align-items: center;
            justify-content: space-between;
            gap: 12px;
            margin: 16px 0;
            padding: 12px 0;
            color: #64748b;
            font-size: 13px;
        `;

        const wrapper = table.closest(
            ".table-container, .table-wrapper, .table-responsive"
        );

        (wrapper || table).insertAdjacentElement("afterend", footer);

        return footer;
    }

    function updateShowingCount(count) {
        const footer = setupPaginationContainer();

        if (!footer) {
            return;
        }

        const startRecord = count === 0 ? 0 : 1;

        footer.innerHTML = `
            <span id="areaShowingCount">
                 Showing ${count === 0 ? 0 : 1} to ${count} of ${count} areas
            </span>

            <div
                class="area-pagination-controls"
                aria-label="Areas page navigation"
                style="
                    display: flex;
                    align-items: center;
                    gap: 6px;
                ">

                <button
                    type="button"
                    disabled
                    aria-label="Previous page"
                    style="
                        min-width: 34px;
                        height: 34px;
                        padding: 6px 10px;
                        border: 1px solid #cbd5e1;
                        border-radius: 6px;
                        background: #fff;
                        color: #64748b;
                        font-size: 17px;
                        opacity: 0.5;
                        cursor: not-allowed;
                    ">‹</button>

                <button
                    type="button"
                    class="area-page-number active"
                    aria-current="page"
                    style="
                        min-width: 34px;
                        height: 34px;
                        padding: 6px 10px;
                        border: 1px solid #2563eb;
                        border-radius: 6px;
                        background: #2563eb;
                        color: #fff;
                        font-size: 13px;
                    ">1</button>

                <button
                    type="button"
                    disabled
                    aria-label="Next page"
                    style="
                        min-width: 34px;
                        height: 34px;
                        padding: 6px 10px;
                        border: 1px solid #cbd5e1;
                        border-radius: 6px;
                        background: #fff;
                        color: #64748b;
                        font-size: 17px;
                        opacity: 0.5;
                        cursor: not-allowed;
                    ">›</button>
            </div>
        `;
    }

    // =========================================
    // CUSTOMER COUNT FOR EACH AREA
    // =========================================
    function getCustomerCount(areaId) {
        return customers.filter(function (customer) {
            return customer.area &&
                String(customer.area.id) === String(areaId);
        }).length;
    }

    // =========================================
    // STATISTICS
    // =========================================
    function updateStatistics() {
        if (totalAreas) {
            totalAreas.textContent = areas.length;
        }

        if (activeAreas) {
            activeAreas.textContent = areas.length;
        }

        if (totalCustomers) {
            totalCustomers.textContent = customers.length;
        }
    }

    // =========================================
    // OPEN MODAL
    // =========================================
    function openModal() {
        if (!modal) {
            return;
        }

        modal.classList.add("show");

        if (form) {
            form.reset();
        }

        if (areaNameInput) {
            areaNameInput.focus();
        }
    }

    if (addButton) {
        addButton.addEventListener("click", openModal);
    }

    // =========================================
    // CLOSE MODAL
    // =========================================
    function closeModal() {
        if (modal) {
            modal.classList.remove("show");
        }
    }

    if (closeButton) {
        closeButton.addEventListener("click", closeModal);
    }

    if (cancelButton) {
        cancelButton.addEventListener("click", closeModal);
    }

    if (modal) {
        modal.addEventListener("click", function (event) {
            if (event.target === modal) {
                closeModal();
            }
        });
    }

    // =========================================
    // SAVE AREA
    // =========================================
    if (form) {
        form.addEventListener("submit", async function (event) {
            event.preventDefault();

            const name = areaNameInput
                ? areaNameInput.value.trim()
                : "";

            if (!name) {
                alert("Please enter area name.");
                return;
            }

            const duplicate = areas.some(function (area) {
                return String(area.name || "").toLowerCase() ===
                    name.toLowerCase();
            });

            if (duplicate) {
                alert("This area already exists.");
                return;
            }

            try {
                const response = await fetch("/api/areas", {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json"
                    },
                    body: JSON.stringify({ name: name })
                });

                if (!response.ok) {
                    throw new Error(await response.text());
                }

                const savedArea = await response.json();

                areas.push(savedArea);

                updateStatistics();
                displayAreas();
                closeModal();
                form.reset();

            } catch (error) {
                console.error("Save area error:", error);
                alert("Unable to save area.");
            }
        });
    }

    // =========================================
    // SEARCH
    // =========================================
    if (searchInput) {
        searchInput.addEventListener("input", function () {
            if (searchInputSecondary) {
                searchInputSecondary.value = searchInput.value;
            }

            displayAreas();
        });
    }

    if (searchInputSecondary) {
        searchInputSecondary.addEventListener("input", function () {
            if (searchInput) {
                searchInput.value = searchInputSecondary.value;
            }

            displayAreas();
        });
    }

    // =========================================
    // EDIT AREA
    // =========================================
    function editArea(area) {
        const newName = prompt("Enter new area name:", area.name);

        if (newName === null) {
            return;
        }

        const name = newName.trim();

        if (!name) {
            alert("Area name cannot be empty.");
            return;
        }

        const duplicate = areas.some(function (item) {
            return String(item.id) !== String(area.id) &&
                String(item.name || "").toLowerCase() === name.toLowerCase();
        });

        if (duplicate) {
            alert("This area already exists.");
            return;
        }

        updateArea(area.id, name);
    }

    // =========================================
    // UPDATE AREA
    // =========================================
    async function updateArea(id, name) {
        try {
            const response = await fetch("/api/areas/" + id, {
                method: "PUT",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify({ name: name })
            });

            if (!response.ok) {
                throw new Error(await response.text());
            }

            const updatedArea = await response.json();

            areas = areas.map(function (area) {
                return String(area.id) === String(id)
                    ? updatedArea
                    : area;
            });

            updateStatistics();
            displayAreas();

        } catch (error) {
            console.error("Update area error:", error);
            alert("Unable to update area. Check your backend PUT endpoint.");
        }
    }

    // =========================================
    // DELETE AREA
    // =========================================
    async function deleteArea(id) {
        const area = areas.find(function (item) {
            return String(item.id) === String(id);
        });

        if (!area) {
            return;
        }

        const confirmed = confirm(
            `Are you sure you want to delete "${area.name}"?`
        );

        if (!confirmed) {
            return;
        }

        try {
            const response = await fetch("/api/areas/" + id, {
                method: "DELETE"
            });

            if (!response.ok) {
                throw new Error(await response.text());
            }

            areas = areas.filter(function (item) {
                return String(item.id) !== String(id);
            });

            updateStatistics();
            displayAreas();

        } catch (error) {
            console.error("Delete area error:", error);
            alert("Unable to delete area.");
        }
    }

    // =========================================
    // ESCAPE HTML
    // =========================================
    function escapeHtml(value) {
        const div = document.createElement("div");
        div.textContent = value == null ? "" : String(value);
        return div.innerHTML;
    }

});
